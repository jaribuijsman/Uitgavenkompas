'use strict';
const assert=require('node:assert/strict');
const A=require('../assets/memento-assistant-core.js');
const K=require('../assets/memento-knowledge-core.js');
globalThis.MementoKnowledgeCore=K;
const task={id:'t1',title:'Kattenbak reinigen',category:'Persoonlijk',room:'Hele huis',kind:'task',repeat:'none',repeatDays:4,priority:false,done:false,history:[],notes:'',deletedAt:''};
const base={version:1,tasks:[task],notes:[],groceries:[{id:'g1',title:'Schoonmaakmiddel',category:'Overig',list:'groceries'}],wishes:[],appointments:[],knowledge:{version:1,deviceId:'test-device',collections:[{id:'home',name:'Huis & Leven',view:'list',icon:'house'}],updatedAt:new Date().toISOString()}};
const journal=K.makeNote({title:'Dagboek',body:'PRIVÉ',collectionId:'inbox'},base);journal.journal={version:1,date:'2026-10-30'};base.notes.push(journal);
const attached=K.makeNote({title:'Bijlage',body:'NIET DELEN',collectionId:'inbox'},base);attached.attachments=[{id:'file123'}];base.notes.push(attached);
const regular=K.makeNote({title:'Woonnotitie',body:'Keuken schoonmaken',collectionId:'inbox'},base);base.notes.push(regular);
const exp=A.snapshot(base,{tasks:true,notes:true,groceries:true,wishes:false});
assert.equal(exp.format,A.EXPORT);
assert.equal(exp.tasks.length,1);
assert.deepEqual(exp.notes.map(n=>n.id),[regular.id]);
assert(!JSON.stringify(exp).includes('PRIVÉ'));
assert(!JSON.stringify(exp).includes('NIET DELEN'));
assert(!JSON.stringify(exp).includes('attachments'));
assert(!JSON.stringify(exp).includes('finances'));
assert.equal(exp.groceries.length,1);
const data={format:A.FORMAT,version:1,changes:[
 {type:'task',id:'t1',expected:{category:'Persoonlijk',kind:'task',repeat:'none'},set:{category:'Huishouden',kind:'routine',repeat:'weekly'},reason:'Terugkerende schoonmaaktaak'},
 {type:'note',id:regular.id,expected:{collectionId:'inbox'},set:{collectionId:'home'},reason:'Onderwerp huis'}
]};
const state=JSON.stringify(base),plan=A.prepare(base,data);
assert.equal(JSON.stringify(base),state);
assert.equal(plan.changes.length,2);
assert.equal(plan.next.tasks[0].category,'Huishouden');
assert.equal(plan.next.notes.find(x=>x.id===regular.id).collectionId,'home');
assert.equal(plan.next.notes.find(x=>x.id===regular.id).body,regular.body);
assert.equal(plan.next.notes.find(x=>x.id===journal.id).body,'PRIVÉ');
const reversed=A.reverse(plan.next,{format:'memento-life-assistant-undo',version:1,changes:plan.changes});
assert.equal(reversed.tasks[0].category,'Persoonlijk');
assert.equal(reversed.notes.find(x=>x.id===regular.id).collectionId,'inbox');
const only=A.prepare(base,data,['task:t1']);
assert.equal(only.changes.length,1);
assert.equal(only.next.notes.find(x=>x.id===regular.id).collectionId,'inbox');
const fail=(fn,message)=>assert.throws(fn,Error,message);
fail(()=>A.prepare({...base,tasks:[{...task,category:'Werk'}]},data),'stale baseline');
fail(()=>A.prepare(base,{...data,changes:[{...data.changes[0],set:{deletedAt:'2026-01-01'},expected:{deletedAt:''}}]}),'destructive field');
fail(()=>A.prepare(base,{...data,changes:[{...data.changes[0],set:{repeat:'weekly'},expected:{repeat:'none'}}]}),'recurrence requires routine');
fail(()=>A.prepare(base,{...data,changes:[data.changes[0],data.changes[0]]}),'duplicate ID');
fail(()=>A.prepare(base,{...data,changes:[{type:'note',id:journal.id,expected:{collectionId:'inbox'},set:{collectionId:'home'},reason:'Move'}]}),'journal excluded');
fail(()=>A.prepare(base,{...data,changes:[{type:'note',id:attached.id,expected:{collectionId:'inbox'},set:{collectionId:'home'},reason:'Move'}]}),'attachment excluded');
const edited=JSON.parse(JSON.stringify(plan.next));edited.tasks[0].notes='Nieuwe persoonlijke opmerking';
const undoEdited=A.reverse(edited,{format:'memento-life-assistant-undo',version:1,changes:plan.changes});
assert.equal(undoEdited.tasks[0].notes,'Nieuwe persoonlijke opmerking');
const conflicting=JSON.parse(JSON.stringify(plan.next));conflicting.tasks[0].category='Werk';
fail(()=>A.reverse(conflicting,{format:'memento-life-assistant-undo',version:1,changes:plan.changes}),'protect later edits');
console.log('PASS assistant privacy, safe bulk planning, selected subset, note revision, stale plan, undo and edit preservation');
